import { useState } from "react";
import { Building2, FileText, Star } from "lucide-react";
import { Dialog, DialogContent, DialogHeader, DialogTitle } from "@/components/ui/dialog";
import { GlassCard, Pill, SectionTitle, timeAgo } from "./primitives";
import { inr, inrCompact } from "@/lib/wms/actions";
import type { PurchaseOrder, WmsState } from "@/lib/wms/types";

